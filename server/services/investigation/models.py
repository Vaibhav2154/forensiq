SeverityLevel = Literal["critical", "high", "medium", "low", "informational"]
ConfidenceLevel = Literal["high", "medium", "low"]
EvidenceLinkType = Literal["observed", "inferred"]
AttackPathStatus = Literal["observed", "inferred", "unconfirmed"]

PlaybookId = Literal[
    "block_ip",
    "lock_user",
    "terminate_user_sessions",
    "kill_process",
    "fix_file_permissions",
    "harden_sshd_config",
    "quarantine_cron_file",
    "upgrade_package",
    "manual_only",
]

FixTier = Literal["tier_1_playbook", "tier_2_config_diff", "tier_3_advisory"]

RemediationStatus = Literal[
    "pending_approval",
    "approved",
    "executed",
    "failed",
    "rejected",
    "rolled_back",
]


# ---------------------------------------------------------------------------
# Sub-Agent 1: Event Analysis
# ---------------------------------------------------------------------------


class EvidenceObservation(BaseModel):
    """A direct, evidence-backed observation anchored to a specific normalized event."""

    observation_id: str = Field(description="Short ID such as obs-001")
    event_id: str = Field(description="Exact NormalizedEvent.event_id supporting this observation")
    evidence_ref_id: str = Field(description="Exact EvidenceReference.reference_id from the event")
    timestamp_utc: str = Field(description="ISO-8601 UTC timestamp of the event")
    scope_key: str = Field(description="Scope key of the observed event")
    summary: str = Field(description="Factual statement of what was directly observed in the log")
    severity: SeverityLevel = Field(default="medium")
    entities: list[str] = Field(
        default_factory=list,
        description="Observed entities such as host:workstation-17, account:alex, ip:203.0.113.25",
    )
    is_anomalous: bool = Field(default=False)


class ObservedIOC(BaseModel):
    """Concrete Indicator of Compromise directly observed in the analyzed logs."""

    ioc_type: Literal["ip", "account", "host", "command", "file_path", "process", "domain", "other"]
    value: str = Field(min_length=1)
    event_ids: list[str] = Field(default_factory=list)
    evidence_ref_ids: list[str] = Field(default_factory=list)
    context: str = Field(default="")


class EventAnalysisOutput(BaseModel):
    """Structured output emitted by the Event Analysis sub-agent."""

    observations: list[EvidenceObservation] = Field(default_factory=list)
    iocs: list[ObservedIOC] = Field(default_factory=list)
    noteworthy_event_ids: list[str] = Field(default_factory=list)
    observed_behaviors: list[str] = Field(
        default_factory=list,
        description="Concise technical behaviors directly seen in the logs",
    )
    entities_summary: list[str] = Field(default_factory=list)
    telemetry_gaps: list[str] = Field(
        default_factory=list,
        description="Important facts NOT visible in the provided logs (e.g. command exit status, stdout, network egress)",
    )


# ---------------------------------------------------------------------------
# Sub-Agent 2: Knowledge Enrichment (Cognee / OKF)
# ---------------------------------------------------------------------------


class KnowledgeQuerySpec(BaseModel):
    """A focused query generated by the Knowledge Enricher for Cognee/OKF lookup."""

    query: str = Field(min_length=2)
    source_type: Literal["mitre_attack", "cve", "any"] = Field(default="mitre_attack")
    rationale: str = Field(default="")


class FollowUpQueryPlan(BaseModel):
    """LLM-generated follow-up retrieval plan for Cognee/OKF."""

    queries: list[KnowledgeQuerySpec] = Field(default_factory=list)
    should_check_cves: bool = Field(default=False)


class EnrichedKnowledgeItem(BaseModel):
    """A verified OKF MITRE ATT&CK or CVE record contextualized for the investigation."""

    record_id: str = Field(description="Exact KnowledgeRecord.record_id from the OKF catalog")
    source_type: Literal["mitre_attack", "cve"]
    source_id: str = Field(description="Exact MITRE ID (e.g. T1021.004) or CVE ID (e.g. CVE-2025-39447)")
    source_version: str = Field(default="")
    name: str = Field(default="")
    description_excerpt: str = Field(default="")
    tactics: list[str] = Field(default_factory=list)
    platforms: list[str] = Field(default_factory=list)
    cvss_score: float | None = Field(default=None)
    relevance_score: float = Field(default=0.0, ge=0.0, le=1.0)
    is_evidence_proof: Literal[False] = False
    supporting_event_ids: list[str] = Field(
        default_factory=list,
        description="Event IDs that make this record relevant investigative context",
    )
    relevance_rationale: str = Field(
        default="",
        description="Why this record provides useful context without claiming proof of compromise",
    )
    missing_confirmation_evidence: list[str] = Field(
        default_factory=list,
        description="Additional forensic artifacts required to confirm this technique/CVE",
    )
    related_mitigations: list[str] = Field(
        default_factory=list,
        description="Related mitigation IDs/names retrieved from Cognee 1-hop graph",
    )
    related_detections: list[str] = Field(
        default_factory=list,
        description="Related data components / detection notes retrieved from Cognee",
    )
    provenance_uri: str = Field(default="")


class KnowledgeEnrichmentOutput(BaseModel):
    """Structured output emitted by the Knowledge Enrichment sub-agent."""

    enriched_records: list[EnrichedKnowledgeItem] = Field(default_factory=list)
    follow_up_queries_executed: list[str] = Field(default_factory=list)
    unmapped_behaviors: list[str] = Field(
        default_factory=list,
        description="Observed behaviors that did not have a strong OKF match",
    )
    cves_checked: bool = Field(default=False)


# ---------------------------------------------------------------------------
# Sub-Agent 3: Sequence Analysis (LSTM-Ready Hook)
# ---------------------------------------------------------------------------


class SequenceCueReview(BaseModel):
    """Review of a single LSTM SequenceCue against retained normalized events."""

    cue_id: str
    scope_key: str
    risk_score: float = Field(ge=0.0, le=1.0)
    threshold: float = Field(ge=0.0, le=1.0)
    corroborated_by_events: bool = Field(default=False)
    supporting_event_ids: list[str] = Field(default_factory=list)
    missing_event_ids: list[str] = Field(default_factory=list)
    assessment: str = Field(
        default="",
        description="Evidence-grounded review of the cue; never treats model score as proof",
    )
    confidence: ConfidenceLevel = Field(default="low")


class SequenceAnalysisOutput(BaseModel):
    """Structured output emitted by the Sequence Analysis sub-agent."""

    status: Literal["analyzed", "skipped_no_cues"] = Field(default="skipped_no_cues")
    reviews: list[SequenceCueReview] = Field(default_factory=list)
    summary: str = Field(
        default="No LSTM sequence cues provided; sequence analysis hook ready for LSTM integration."
    )


# ---------------------------------------------------------------------------
# Sub-Agent 4: Correlation & Timeline Analysis
# ---------------------------------------------------------------------------


class TimelineEntry(BaseModel):
    """Chronological event entry anchored to an observed normalized event."""

    timestamp_utc: str = Field(description="YYYY-MM-DD HH:MM:SS UTC")
    timestamp_ist: str = Field(description="YYYY-MM-DD HH:MM:SS IST")
    event_id: str
    evidence_ref_id: str
    scope_key: str
    event_type: str
    actor: str = Field(default="unknown")
    source_ip: str = Field(default="")
    host: str = Field(default="")
    summary: str
    significance: SeverityLevel = Field(default="medium")


class EntityRelationship(BaseModel):
    """A relationship between observed entities/events, labeled observed vs. inferred."""

    source_entity: str
    relation: str
    target_entity: str
    evidence_type: EvidenceLinkType = Field(
        description="Use 'observed' only when directly recorded in logs; otherwise 'inferred'"
    )
    supporting_event_ids: list[str] = Field(default_factory=list)
    reasoning: str = Field(default="")
    confidence: ConfidenceLevel = Field(default="medium")


class CorrelationTimelineOutput(BaseModel):
    """Structured output emitted by the Correlation & Timeline sub-agent."""

    timeline: list[TimelineEntry] = Field(default_factory=list)
    relationships: list[EntityRelationship] = Field(default_factory=list)
    correlated_scopes: list[str] = Field(default_factory=list)
    temporal_patterns: list[str] = Field(
        default_factory=list,
        description="Observed time-window patterns (e.g. rapid failed logins followed by success in 48s)",
    )


# ---------------------------------------------------------------------------
# Sub-Agent 5: Attack-Path Hypothesis Analysis
# ---------------------------------------------------------------------------


class AttackPathNode(BaseModel):
    """A node in the attack-path hypothesis graph."""

    node_id: str = Field(description="Short alphanumeric ID such as step_1")
    label: str
    stage: str = Field(
        description="Kill-chain or MITRE tactic stage (e.g. Initial Access, Credential Access, Privilege Escalation)"
    )
    status: AttackPathStatus = Field(
        description="'observed' for directly logged facts, 'inferred' for reasoned hypotheses, 'unconfirmed' for plausible next steps lacking evidence"
    )
    event_ids: list[str] = Field(default_factory=list)
    knowledge_source_ids: list[str] = Field(
        default_factory=list,
        description="ONLY verified MITRE ATT&CK / CVE IDs from the enriched knowledge catalog",
    )
    confidence: ConfidenceLevel = Field(default="medium")
    notes: str = Field(default="")


class AttackPathEdge(BaseModel):
    """A directed edge in the attack-path hypothesis graph."""

    source_node_id: str
    target_node_id: str
    label: str
    status: AttackPathStatus
    evidence_event_ids: list[str] = Field(default_factory=list)
    reasoning: str = Field(default="")
    confidence: ConfidenceLevel = Field(default="medium")


class AttackPathOutput(BaseModel):
    """Structured output emitted by the Attack-Path Hypothesis sub-agent."""

    hypothesis_title: str = Field(default="Investigation Attack-Path Hypothesis")
    summary: str = Field(default="")
    nodes: list[AttackPathNode] = Field(default_factory=list)
    edges: list[AttackPathEdge] = Field(default_factory=list)
    missing_evidence: list[str] = Field(
        default_factory=list,
        description="Explicitly visible evidence gaps preventing full confirmation",
    )
    alternative_hypotheses: list[str] = Field(
        default_factory=list,
        description="Plausible benign or alternative explanations for the observed sequence",
    )
    mermaid_diagram: str = Field(default="")


# ---------------------------------------------------------------------------
# Orchestrator Review & Conflict Resolution
# ---------------------------------------------------------------------------


class ReviewIssue(BaseModel):
    """A conflict, grounding failure, or coverage gap identified by the orchestrator."""

    issue_type: Literal[
        "hallucinated_knowledge_id",
        "missing_evidence_ref",
        "conflict",
        "coverage_gap",
    ]
    target_agent: str
    description: str
    resolution_action: str = Field(default="")


class OrchestratorReviewOutput(BaseModel):
    """Structured evaluation emitted by the Orchestrator Review node."""

    approved: bool = Field(default=True)
    issues: list[ReviewIssue] = Field(default_factory=list)
    remediation_justified: bool = Field(
        default=False,
        description="True only when supported findings justify proposing preventive/response actions",
    )
    refinement_targets: list[Literal["knowledge_enricher", "attack_path_analyst"]] = Field(
        default_factory=list
    )
    refinement_instructions: str = Field(default="")
    conflict_resolution_notes: list[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Sub-Agent 6: Recommendation Drafting (Approval-Gated)
# ---------------------------------------------------------------------------


class RecommendationDraftItem(BaseModel):
    """Gemini-structured-output-safe recommendation draft (no arbitrary dict fields)."""

    recommendation_id: str = Field(description="Short ID such as rec-001")
    priority: Literal["immediate", "short_term", "long_term"]
    title: str
    target: str = Field(description="System, account, network control, or policy targeted")
    action: str = Field(description="Concrete action to review and authorize")
    expected_effect: str = Field(description="Expected security impact of taking this action")
    supporting_finding_ids: list[str] = Field(default_factory=list)
    evidence_event_ids: list[str] = Field(default_factory=list)
    knowledge_mitigation_ids: list[str] = Field(
        default_factory=list,
        description="Verified MITRE mitigation IDs (e.g. M1032) if retrieved from Cognee",
    )
    requires_human_approval: Literal[True] = True
    auto_executable: Literal[False] = False
    rollback_notes: str = Field(default="")


class RecommendationDraftOutput(BaseModel):
    """Gemini-structured-output-safe wrapper emitted by the Recommendation Drafting LLM."""

    status: Literal["drafted", "skipped_unjustified"] = Field(default="skipped_unjustified")
    recommendations: list[RecommendationDraftItem] = Field(default_factory=list)
    rationale: str = Field(default="")


class RecommendationItem(BaseModel):
    """An evidence-linked, human-approval-gated remediation or containment proposal."""

    recommendation_id: str = Field(description="Short ID such as rec-001")
    priority: Literal["immediate", "short_term", "long_term"]
    title: str
    target: str = Field(description="System, account, network control, or policy targeted")
    action: str = Field(description="Concrete action to review and authorize")
    expected_effect: str = Field(description="Expected security impact of taking this action")
    supporting_finding_ids: list[str] = Field(default_factory=list)
    evidence_event_ids: list[str] = Field(default_factory=list)
    knowledge_mitigation_ids: list[str] = Field(
        default_factory=list,
        description="Verified MITRE mitigation IDs (e.g. M1032) if retrieved from Cognee",
    )
    requires_human_approval: Literal[True] = True
    auto_executable: Literal[False] = False
    rollback_notes: str = Field(default="")

    # HITL TUI Remediation extensions (backward-compatible defaults)
    fixable_via_tui: bool = Field(
        default=False,
        description="True when a deterministic Tier-1 or Tier-2 local TUI playbook applies",
    )
    fix_tier: FixTier = Field(default="tier_3_advisory")
    playbook_id: PlaybookId = Field(default="manual_only")
    playbook_params: dict[str, str] = Field(
        default_factory=dict,
        description="Validated key-value parameters for the local TUI playbook",
    )
    execution_status: RemediationStatus = Field(default="pending_approval")


class RecommendationOutput(BaseModel):
    """Structured output emitted by the Recommendation Drafting sub-agent."""

    status: Literal["drafted", "skipped_unjustified"] = Field(default="skipped_unjustified")
    recommendations: list[RecommendationItem] = Field(default_factory=list)
    rationale: str = Field(default="")


class RemediationAuditEvent(BaseModel):
    """Audit event synced from the local TUI when an analyst approves, rejects, or rolls back a fix."""

    recommendation_id: str
    execution_status: RemediationStatus
    receipt_id: str | None = None
    executed_by: str | None = None
    notes: str | None = None
    recorded_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


# ---------------------------------------------------------------------------
# Final Investigation Synthesis & Audit Trail
# ---------------------------------------------------------------------------


class InvestigationFinding(BaseModel):
    """A material finding with explicit separation between evidence, inference, and uncertainty."""

    finding_id: str = Field(description="Short ID such as find-001")
    title: str
    severity: SeverityLevel
    confidence: ConfidenceLevel
    observed_facts: list[str] = Field(
        default_factory=list,
        description="Direct log-supported facts citing event_ids",
    )
    inferences: list[str] = Field(
        default_factory=list,
        description="Analyst hypotheses inferred from the facts and context",
    )
    uncertainty: str = Field(
        default="",
        description="What remains unconfirmed or ambiguous about this finding",
    )
    supporting_event_ids: list[str] = Field(default_factory=list)
    evidence_ref_ids: list[str] = Field(default_factory=list)
    knowledge_source_ids: list[str] = Field(default_factory=list)


class FinalSynthesisDraft(BaseModel):
    """LLM-generated synthesis portion assembled by the Orchestrator Synthesize node."""

    overall_threat_level: SeverityLevel
    overall_confidence: ConfidenceLevel
    executive_summary: str
    findings: list[InvestigationFinding] = Field(default_factory=list)
    potential_impact: list[str] = Field(default_factory=list)
    uncertainty_and_gaps: list[str] = Field(default_factory=list)


class AuditEntry(BaseModel):
    """Auditable record of a single orchestrator or sub-agent execution step."""

    step_id: str
    node_name: str
    agent_role: str
    status: Literal["completed", "skipped", "retried", "fallback", "error"]
    model_name: str = Field(default="")
    api_key_slot: str = Field(default="")
    started_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    duration_ms: float = Field(default=0.0, ge=0.0)
    input_summary: str = Field(default="")
    output_summary: str = Field(default="")
    notes: list[str] = Field(default_factory=list)


class InvestigationResult(BaseModel):
    """Complete evidence-backed investigation output produced by the LangGraph orchestrator."""

    schema_version: str = Field(default="1.0")
    investigation_id: str
    status: Literal["completed", "completed_with_warnings"] = Field(default="completed")
    overall_threat_level: SeverityLevel = Field(default="informational")
    overall_confidence: ConfidenceLevel = Field(default="low")
    executive_summary: str = Field(default="")
    observations: list[EvidenceObservation] = Field(default_factory=list)
    findings: list[InvestigationFinding] = Field(default_factory=list)
    retrieved_knowledge: list[EnrichedKnowledgeItem] = Field(default_factory=list)
    timeline: list[TimelineEntry] = Field(default_factory=list)
    relationships: list[EntityRelationship] = Field(default_factory=list)
    attack_path: AttackPathOutput = Field(default_factory=AttackPathOutput)
    iocs: list[ObservedIOC] = Field(default_factory=list)
    recommendations: list[RecommendationItem] = Field(default_factory=list)
    recommendation_status: Literal["drafted", "skipped_unjustified"] = Field(
        default="skipped_unjustified"
    )
    remediation_history: list[RemediationAuditEvent] = Field(default_factory=list)
    sequence_assessment: SequenceAnalysisOutput = Field(default_factory=SequenceAnalysisOutput)
    potential_impact: list[str] = Field(default_factory=list)
    uncertainty_and_gaps: list[str] = Field(default_factory=list)
    guardrail_warnings: list[str] = Field(default_factory=list)
    refinement_rounds_executed: int = Field(default=0, ge=0)
    audit_trail: list[AuditEntry] = Field(default_factory=list)
    rendered_summary: str = Field(default="")
    rendered_markdown_report: str = Field(default="")
    completed_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    processing_time_ms: float = Field(default=0.0, ge=0.0)
